"""Render every figure in figs.py to ../../grim.js (data only).
Run:  python3 tools/art/build.py     Preview:  python3 tools/art/sheet.py out.png [names]"""
import json, os
from px import render, bbox, to_rows, palette
from figs import FIGS
SIZES = (('mini', 0.34, 3), ('a', 0.667, 3), ('hi', 1.0, 4))
out = {}
for name, fn in FIGS.items():
    f0, f1 = fn(0), fn(1)
    e = {'mats': [[m['name'], m['old'], 1 if m['bright'] else 0] for m in f0.mats], 'pal': palette(f0)}
    for key, sc, lv in SIZES:
        g0, g1 = render(f0, sc, lv), render(f1, sc, lv)
        box = bbox([g0, g1]) if key != 'mini' else bbox([g0])
        e[key] = to_rows(g0, box)
        if key != 'mini':
            r1 = to_rows(g1, box)
            if r1 != e[key]: e[key + '2'] = r1
    out[name] = e
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, '..', '..', 'grim.js'), 'w') as fh:
    fh.write('/* grim.js: battle sprite data, generated by tools/art/build.py. Do not edit by hand.\n'
             '   Per sprite: mats [name, old palette letters, bright], pal (5 letters per material, dark to light),\n'
             '   and pixel rows at three sizes: mini (map), a (regular), hi (bosses); a2/hi2 are the second idle frame. */\n')
    fh.write('const GRIM = {\n')
    for n, e in out.items():
        fh.write('  %s: %s,\n' % (n, json.dumps(e, separators=(',', ':'))))
    fh.write('};\n')
print(len(out), 'sprites', os.path.getsize(os.path.join(here, '..', '..', 'grim.js')), 'bytes')
