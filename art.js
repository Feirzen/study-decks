/* ===================================================================
   art.js: the 2026 art pass for Battle ("Grim" sprites)
   - grim.js holds the pixel data (generated by tools/art/build.py).
   - Every hero, foe and boss is redrawn with real proportions at three
     sizes: mini (the map), regular, and hi-res (bosses).
   - Old recolors keep working: VARIANTS ("slime~jelly") and hue shifts
     ("golem~h140") are written against the old palette letters, so each
     material here remembers which old letters it stands in for and the
     recolor is rebuilt as a five-tone ramp.
   - Sprites have a second idle frame; a slow ticker swaps between them.
   Loaded last, so its overrides win. Remove this file and grim.js from
   index.html to get the old art back.
   =================================================================== */
(function () {
  if (typeof GRIM === "undefined") return;
  const ALPHA = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
  /* old stand-alone recolors that were copies of another sprite */
  const ALIAS = { slime_ice: "slime", slime_magma: "slime", bat_blood: "bat", ghost_violet: "ghost" };
  /* sprites that only ever show up as bosses: always drawn hi-res */
  const BOSS_ONLY = { slimeking: 1, golem: 1, lich: 1, dragon: 1, commander: 1, scientist: 1, showman: 1, hooded: 1 };

  /* what each alias changed, read from the old data before anything is replaced */
  const ALIAS_OV = {};
  Object.keys(ALIAS).forEach(k => {
    const a = SPRITES[k], b = SPRITES[ALIAS[k]]; if (!a || !b) return;
    const ov = {}; Object.keys(a.pal).forEach(c => { if (a.pal[c] !== b.pal[c]) ov[c] = a.pal[c]; });
    ALIAS_OV[k] = ov;
  });

  /* ---------- colour helpers ---------- */
  function hsl(hex) {
    const n = parseInt(hex.slice(1), 16), r = (n >> 16 & 255) / 255, g = (n >> 8 & 255) / 255, b = (n & 255) / 255;
    const mx = Math.max(r, g, b), mn = Math.min(r, g, b), l = (mx + mn) / 2;
    if (mx === mn) return [0, 0, l];
    const d = mx - mn, s = l > 0.5 ? d / (2 - mx - mn) : d / (mx + mn);
    const h = mx === r ? (g - b) / d + (g < b ? 6 : 0) : mx === g ? (b - r) / d + 2 : (r - g) / d + 4;
    return [h * 60, s, l];
  }
  function hex(h, s, l) {
    h = ((h % 360) + 360) % 360; s = Math.max(0, Math.min(1, s)); l = Math.max(0, Math.min(1, l));
    const f = n => { const k = (n + h / 30) % 12, a = s * Math.min(l, 1 - l); return Math.round(255 * (l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1)))); };
    return "#" + [f(0), f(8), f(4)].map(x => x.toString(16).padStart(2, "0")).join("");
  }
  const toward = (h, target, by) => { const d = ((target - h + 540) % 360) - 180; return h + Math.max(-by, Math.min(by, d)); };
  /* one flat colour -> five tones, shadows leaning cool and lights leaning warm */
  function rampFrom(c, bright) {
    if (!/^#[0-9a-f]{6}$/i.test(c)) return null;
    const [h, s0, l0] = hsl(c), s = bright ? s0 : s0 * 0.62, l = bright ? l0 : Math.max(0.17, Math.min(0.8, l0));
    if (bright) return [hex(h, s, l * 0.35), hex(h, s, l * 0.65), hex(h, s, l), hex(toward(h, 55, 8), s, l + (1 - l) * 0.5), hex(h, s * 0.5, l + (1 - l) * 0.9)];
    return [
      hex(toward(h, 250, 14), s * 0.95, l * 0.3),
      hex(toward(h, 250, 8), s, l * 0.58),
      hex(h, s, l),
      hex(toward(h, 55, 6), s * 0.95, l + (1 - l) * 0.34),
      hex(toward(h, 55, 10), s * 0.75, l + (1 - l) * 0.68),
    ];
  }
  function recolor(G, pal, ov) {
    if (!ov) return;
    G.mats.forEach((m, i) => {
      for (const ch of m[1]) {
        if (!ov[ch]) continue;
        const r = rampFrom(ov[ch], !!m[2]);
        if (r) for (let t = 0; t < 5; t++) pal[ALPHA[i * 5 + t]] = r[t];
        break;
      }
    });
  }

  /* ---------- getSprite: new art first, old data for everything else ---------- */
  const _oldGet = getSprite, _cache = {};
  function grimOf(name) {
    const core = String(name).replace(/~h-?\d+$/, ""), base = core.split("~")[0];
    return GRIM[ALIAS[base] || base] ? (ALIAS[base] || base) : null;
  }
  getSprite = function (name) {
    name = String(name);
    if (_cache[name]) return _cache[name];
    const hm = /^(.*)~h(-?\d+)$/.exec(name), core = hm ? hm[1] : name, base = core.split("~")[0];
    const gname = ALIAS[base] || base, G = GRIM[gname];
    if (!G) return _oldGet(name);
    const pal = Object.assign({}, G.pal);
    if (ALIAS[base]) recolor(G, pal, ALIAS_OV[base]);
    if (core !== base) recolor(G, pal, VARIANTS[core]);
    if (hm) Object.keys(pal).forEach(k => { const [h, s, l] = hsl(pal[k]); if (s >= 0.12) pal[k] = hex(h + +hm[2], s, l); });
    return (_cache[name] = { pal, rows: G.a, grim: G, gname });
  };

  /* ---------- grids ---------- */
  const _oldGrid = spriteGrid, _grids = {};
  let FRAME = 0;
  spriteGrid = function (name, kind, fr) {
    const sp = getSprite(name);
    if (!sp || !sp.grim) return _oldGrid(name);
    kind = kind || "a";
    const two = fr && sp.grim[kind + "2"] ? 1 : 0, key = name + "|" + kind + "|" + two;
    if (_grids[key]) return _grids[key];
    const rows = sp.grim[kind + (two ? "2" : "")], pal = sp.pal, n = rows.length, m = rows[0].length;
    const at = (y, x) => (y >= 0 && y < n && x >= 0 && x < m && pal[rows[y][x]]) || null;
    const out = [];
    for (let y = -1; y <= n; y++) {
      const row = [];
      for (let x = -1; x <= m; x++) {
        const c = at(y, x);
        row.push(c ? c : (at(y - 1, x) || at(y + 1, x) || at(y, x - 1) || at(y, x + 1)) ? OUTLINE : null);
      }
      out.push(row);
    }
    return (_grids[key] = out);
  };

  /* the old code asked for "N screen pixels per sprite pixel" of a 16px sprite;
     the new sprites are 2x (regular) or 3x (hi-res) as dense, so scale down. */
  function plan(sp, scale) {
    const hi = scale >= 5 || BOSS_ONLY[sp.gname];
    return { kind: hi ? "hi" : "a", k: hi ? (scale >= 3 ? 2 : 1) : Math.max(1, Math.round(scale / 2)) };
  }
  const _oldDraw = drawSprite;
  drawSprite = function (canvas, name, scale, flip) {
    const sp = getSprite(name);
    if (!sp || !canvas) return;
    if (!sp.grim) return _oldDraw(canvas, name, scale, flip);
    const p = plan(sp, scale), grid = spriteGrid(name, p.kind, FRAME), n = grid.length, m = grid[0].length, k = p.k;
    if (canvas.width !== m * k || canvas.height !== n * k) {
      canvas.width = m * k; canvas.height = n * k;
      canvas.style.width = (m * k) + "px"; canvas.style.height = (n * k) + "px";
    }
    const g = canvas.getContext("2d");
    g.imageSmoothingEnabled = false;
    g.clearRect(0, 0, canvas.width, canvas.height);
    for (let y = 0; y < n; y++) for (let x = 0; x < m; x++) {
      const col = grid[y][x]; if (!col) continue;
      g.fillStyle = col; g.fillRect((flip ? m - 1 - x : x) * k, y * k, k, k);
    }
    canvas.dataset.two = sp.grim[p.kind + "2"] ? "1" : "";
  };

  /* idle animation: swap to the second frame and back */
  setInterval(() => {
    if (document.hidden) return;
    FRAME ^= 1;
    document.querySelectorAll('canvas[data-sprite][data-two="1"]').forEach(cv => {
      if (cv.hasAttribute("data-ghost") || cv.closest(".frozen, .fallen, .sil")) return;
      drawSprite(cv, cv.dataset.sprite, +(cv.dataset.scale || 4), cv.hasAttribute("data-flip"));
    });
  }, 520);

  /* death shatter: the new sprites have four times the pixels, so thin the burst */
  const _oldBurst = spriteBurst;
  spriteBurst = function () {
    const real = fxAdd, CAP = 300;
    fxAdd = list => real(list.length > CAP ? list.filter(() => Math.random() < CAP / list.length) : list);
    try { return _oldBurst.apply(this, arguments); } finally { fxAdd = real; }
  };

  /* the map draws at one screen pixel per sprite pixel: use the mini size there */
  if (typeof spriteImg === "function") {
    const _oldImg = spriteImg;
    spriteImg = function (name, flip) {
      const sp = getSprite(name);
      if (!sp || !sp.grim) return _oldImg(name, flip);
      const key = "g|" + name + (flip ? "|f" : "");
      if (MS.cache[key]) return MS.cache[key];
      const grid = spriteGrid(name, "mini"), n = grid.length, m = grid[0].length;
      const c = document.createElement("canvas"); c.width = m; c.height = n;
      const g = c.getContext("2d");
      for (let y = 0; y < n; y++) for (let x = 0; x < m; x++) {
        const col = grid[y][x]; if (!col) continue;
        g.fillStyle = col; g.fillRect(flip ? m - 1 - x : x, y, 1, 1);
      }
      return (MS.cache[key] = c);
    };
  }

  /* layout: taller fighters need a taller arena, and boxed portraits must keep their shape */
  const css = document.createElement("style");
  css.textContent = `
  .arena { height: 232px; }
  .stage { height: 150px; }
  @media (max-width: 640px) { .arena { height: 216px; } }
  @media (min-width: 940px) { .battle .arena { height: clamp(290px, 44vh, 380px); } }
  .slotart canvas, .tw-por canvas, .herorow canvas { width: auto !important; height: auto !important; max-width: 100%; max-height: 100%; }
  .tw-por canvas { max-width: 52px; max-height: 52px; }
  .slotart.sm canvas { max-height: 50px; }
  `;
  document.head.appendChild(css);

  window.GRIM_ART = { getSprite, grimOf, plan, rampFrom };
  if (typeof render === "function" && document.getElementById("app") && document.getElementById("app").children.length) { try { render(); } catch (e) { } }
})();
